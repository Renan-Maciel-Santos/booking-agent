"""Unit tests for date-independent demo scheduling and parser consistency."""

from datetime import UTC, date, datetime, time

import pytest

from booking_agent.domain.booking_intent import IntentType
from booking_agent.integrations.llm.fake_intent_parser import FakeIntentParser
from scripts.demo_conversation import compute_demo_dates, format_demo_date_phrase
from tests.fakes.fake_clock import FakeClock

# 7 consecutive days starting on Monday (2026-10-19) through Sunday (2026-10-25)
_SEVEN_DAYS_OF_WEEK = [
    date(2026, 10, 19),  # Monday (0)
    date(2026, 10, 20),  # Tuesday (1)
    date(2026, 10, 21),  # Wednesday (2)
    date(2026, 10, 22),  # Thursday (3)
    date(2026, 10, 23),  # Friday (4)
    date(2026, 10, 24),  # Saturday (5)
    date(2026, 10, 25),  # Sunday (6)
]


@pytest.mark.unit
@pytest.mark.parametrize("base_date", _SEVEN_DAYS_OF_WEEK)
def test_compute_demo_dates_never_falls_on_sunday_and_reschedule_is_posterior(
    base_date: date,
) -> None:
    """Ensure computed demo dates never land on Sunday and reschedule is strictly after booking."""
    booking_date, reschedule_date = compute_demo_dates(base_date)

    # 6 is Sunday (closed according to db/seeds/demo.sql)
    assert booking_date.weekday() != 6, f"Booking date {booking_date} must not be Sunday"
    assert reschedule_date.weekday() != 6, f"Reschedule date {reschedule_date} must not be Sunday"
    assert reschedule_date > booking_date, (
        f"Reschedule date {reschedule_date} must be strictly after booking date {booking_date}"
    )


@pytest.mark.unit
@pytest.mark.parametrize("base_date", _SEVEN_DAYS_OF_WEEK)
@pytest.mark.asyncio
async def test_demo_date_phrases_resolve_identically_in_fake_intent_parser(
    base_date: date,
) -> None:
    """Prove that date phrases generated by the demo resolve identically in FakeIntentParser."""
    booking_date, reschedule_date = compute_demo_dates(base_date)
    booking_phrase = format_demo_date_phrase(booking_date)
    reschedule_phrase = format_demo_date_phrase(reschedule_date)

    # Inject clock representing 12:00 UTC on the simulated base_date
    simulated_now = datetime.combine(base_date, time(12, 0), tzinfo=UTC)
    clock = FakeClock(simulated_now)
    parser = FakeIntentParser(clock=clock)

    # 1. Booking message check
    book_msg = f"Olá! Gostaria de agendar um corte para {booking_phrase} às 15h."
    parsed_book = await parser.parse(book_msg)
    assert parsed_book.intent == IntentType.BOOK
    assert parsed_book.local_date == booking_date
    assert parsed_book.local_time == time(15, 0)

    # 2. Reschedule message check
    reschedule_msg = f"Gostaria de remarcar para {reschedule_phrase} às 16h."
    parsed_reschedule = await parser.parse(reschedule_msg)
    assert parsed_reschedule.intent == IntentType.RESCHEDULE
    assert parsed_reschedule.local_date == reschedule_date
    assert parsed_reschedule.local_time == time(16, 0)
